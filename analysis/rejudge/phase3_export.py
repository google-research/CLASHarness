"""Phase 3: freeze the judge-provenance result into a committed artifact.

The working directory for this ablation ($CLASHARNESS_DATA_ROOT/rejudge)
holds ~90MB of judge prompts and three verdict files, none of which belong in
the paper repository. Following the convention set by src/report/*.json --
"committed under src/report, so the self-check runs from a clean clone with no
source checkout present" (analysis/corpus.py:69) -- this writes one compact
JSON with every number the paper cites, so analysis/judge_ablation.py --check
can verify the prose without the raw sweep.

Usage:
    python3 phase3_export.py
"""

from __future__ import annotations

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import phase2_recompute as p2  # noqa: E402
import replay_core as rc  # noqa: E402

OUT = os.path.join(rc.WORK, "rejudge")
DEST = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                    os.pardir, "src", "report", "judge_ablation.json")


def main() -> int:
    src = os.path.join(OUT, "phase2_summary.json")
    if not os.path.exists(src):
        print(f"missing {src}; run phase2_recompute.py first")
        return 1
    s = json.load(open(src, encoding="utf-8"))

    # Per-model verdict counts, so the denominators in the prose are checkable.
    rounds = p2.load_rounds()
    slugs = [x for x, *_ in rc.PANEL]
    pairs_per_model = {
        slug: sum(1 for r in rounds.get(slug, []) for c in r["checks"]
                  if c.get("pair_id"))
        for slug in slugs
    }

    fid = json.load(open(os.path.join(OUT, "phase0_summary.json"),
                         encoding="utf-8"))
    out = {
        "_comment": (
            "Judge-provenance ablation. Generated by analysis/rejudge/"
            "phase3_export.py from the offline replay + judge-swap sweep; see "
            "analysis/rejudge/README-less pipeline docstrings. Verified by "
            "analysis/judge_ablation.py --check."
        ),
        "replay_fidelity": {
            "deterministic_checks": fid["totals"]["det_total"],
            "deterministic_match": fid["totals"]["det_match"],
            "fidelity": fid["det_fidelity"],
            "rounds": fid["totals"]["rounds"],
            "judge_pairs": fid["totals"]["pairs"],
        },
        "pairs_per_model": pairs_per_model,
        "rate": s["rate"],
        "score": s["score"],
        "ranks": s["ranks"],
        "settings": s["settings"],
        "summary": s["summary"],
        "ensemble_health": s["ensemble_health"],
        "missing_pair_bounds": {
            j: {k: v for k, v in m.items() if k != "per_model"}
            for j, m in s["missing_pair_bounds"].items()
        },
        "gemini_3_7_decomposition": s["gemini_3_7_decomposition"],
        "agreement": s.get("agreement", {}),
        "panel_coverage": s["panel_coverage"],
        "score_summary": s["score_summary"],
        "family_delta": s["family_delta"],
    }
    dest = os.path.normpath(DEST)
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    with open(dest, "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=1, sort_keys=True)
    print(f"wrote {dest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
