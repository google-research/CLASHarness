"""Guard: every result-table body in main.tex is a verbatim run of rows that
its generator prints.

WHY THIS EXISTS. Every result table in the paper is generated by a script in
analysis/ and the .tex says "paste verbatim" for each. Nothing enforced that,
and it failed twice without anyone noticing:

  tab:coverage  the generator printed a literal ">=1"; someone repaired it to
                $\\ge$1 in main.tex, and from that edit onward the body and its
                generator disagreed by construction.
  tab:corpora   the whole descriptive half was typed by hand. Regenerating it
                confirmed the figures but corrected one -- the paired-round
                count is a ceiling of 573, and provider errors leave as few as
                555 in a given cell. (That float no longer exists: it is now
                tab:corpora-design plus tab:ablation's panel (c).)

A number that is right today and typed by hand is a number that goes stale the
next time the corpus is rebuilt. This turns "paste verbatim" from a comment
into a check.

WHAT IT CHECKS. For each label, EACH of its generator blocks must appear
EXACTLY ONCE as a contiguous run inside that table's tabular. Rows belonging
to no block (column headers, group rows, \\cmidrule, \\toprule) are
hand-written on purpose and are reported as one count per LABEL -- not per
block, which would count a sibling panel's rows as hand-written -- so a header
that quietly grows is still visible.

TWO REGIONS, NOT ONE. A block may target the tabular or the NOTE region --
whatever sits between \\end{tabular} and \\end{table}. tab:ablation and
tab:coverage each ended in a \\multicolumn spanning every column, and a
\\multicolumn wider than the columns it spans dumps the whole overhang on the
LAST one: the ablation note alone opened a 30.2pt hole in front of column 7
and nowhere else. The notes now sit outside the tabular in a minipage, which
decouples them from the column widths for good, and the generators print them
under their own markers so they stay verified rather than becoming the two
hand-typed lines in an otherwise generated paper. The minipage scaffolding
itself is hand-written and counted as such.

USAGE
    python3 src/verify_table_bodies.py            # runs the generators
    python3 src/verify_table_bodies.py --cached   # reuse /tmp/verify_*.txt

Exit status is 1 on any mismatch, so it can gate a commit.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ANALYSIS = os.path.join(HERE, "analysis")

# label -> [(script, marker[, region[, argv]]), ...]
# region is "tabular" (default) or "note"; see the two-regions note above.
# argv is the argument list the generator is invoked with (default none), and
# it is part of the cache key -- difficulty_bands.py prints a different table
# per reasoning effort and the three must not share a cached log.
#
# The marker is matched as a substring and has to stay distinctive: a
# generator that prints a second block (table1_v8 used to print a COMPACT
# nine-page fallback under a near-identical heading) will otherwise be matched
# on the wrong one, silently.
#
# A LABEL MAY LIST MORE THAN ONE BLOCK. tab:ablation is fed by two different
# scripts -- panels (a) and (b) from ablation.py, panel (c) from
# generator_ablation.py -- since the merge pass folded the old tab:corpora
# into it as a third panel. Each block is required to appear exactly once on
# its own; nothing here checks their ORDER inside the tabular, because a
# contiguous-run match per block already pins each panel's internal rows and
# the panels are separated by hand-written rules the blocks do not span.
SPEC = {
    # The three efforts are one script run three ways. Each invocation prints
    # exactly one block, so the markers could not collide within a single log,
    # but they are spelled out per effort anyway: a marker that says which
    # table it feeds is the thing that catches a SPEC row wired to the wrong
    # argv, which substring-matching "LaTeX body for T1" would not.
    "tab:main":          [("difficulty_bands.py",
                           "LaTeX body for T1 across all efforts",
                           "tabular", ("all",))],
    # tab:main-high is the same fourteen rows tab:main already shows, plus the
    # easy-hard contrast the stacked table drops for width. It gets its own
    # SPEC row rather than being assumed to follow from tab:main: the two are
    # different code paths in difficulty_bands.py -- stacked vs single-effort --
    # and only the single-effort one still computes delta at all.
    "tab:main-high":     [("difficulty_bands.py",
                           "LaTeX body for T1 at high effort",
                           "tabular", ("high",))],
    "tab:main-medium":   [("difficulty_bands.py",
                           "LaTeX body for T1 at medium effort",
                           "tabular", ("medium",))],
    "tab:main-low":      [("difficulty_bands.py",
                           "LaTeX body for T1 at low effort",
                           "tabular", ("low",))],
    # "across all efforts" is not decoration. cost.py's block now carries three
    # think levels per API model, and the bare "LaTeX body for T2" it used to
    # print is a SUBSTRING of the new marker -- so leaving this row alone would
    # have kept passing while saying nothing about which shape it verified.
    # Spelling out the shape makes a future single-effort revert fail loudly
    # here instead of matching by accident.
    "tab:cost":          [("cost.py",
                           "LaTeX body for T2 across all efforts")],
    # Same string, different script, so these two never race: gen_block only
    # ever searches one generator's own stdout.
    "tab:concentration": [("clustering_v8.py",      "LaTeX body for T2")],
    "tab:validity":      [("check_split_v8.py",     "LaTeX body for T3")],
    "tab:capability":    [("capability_axes_v8.py", "LaTeX body for T8")],
    # One script, THREE floats, and the markers must not nest -- the same trap
    # documented for generator_ablation.py below. "LaTeX body for T10" alone
    # would be a substring of all three markers, so gen_block would resolve
    # every label to whichever block printed first and report a clean pass
    # having never looked at the other two. "main", "full" and "robustness"
    # are chosen because no one of them contains another. Keep it that way.
    # main = the narrow wraptable in the body; full = the same two arms with
    # per-arm n and the dose tiers, in the appendix; robustness = the
    # re-estimation matrix.
    "tab:conflict-gate": [("conflict_gate_v8.py",
                           "LaTeX body for T10 main")],
    "tab:conflict-gate-full": [("conflict_gate_v8.py",
                                "LaTeX body for T10 full")],
    "tab:conflict-gate-app": [("conflict_gate_v8.py",
                               "LaTeX body for T10 robustness")],
    "tab:coverage":      [("coverage_v8.py",        "LaTeX body for T9"),
                          ("coverage_v8.py",
                           "LaTeX note under the coverage table", "note")],
    "tab:corpora-design": [("generator_ablation.py",
                            "LaTeX body for the corpora design")],
    # Three bodies, one per tabular*: the float sets each panel in its own
    # environment, so the rules that close one and open the next fall between
    # blocks rather than inside one, and each block stays a contiguous run.
    "tab:ablation-app":  [("ablation.py",
                           "LaTeX body for the step-budget panel"),
                          ("ablation.py",
                           "LaTeX body for the visual-modality panel"),
                          ("generator_ablation.py",
                           "LaTeX body for the corpora outcome"),
                          ("generator_ablation.py",
                           "LaTeX note under the ablation table", "note")],
}

# ONE SCRIPT, TWO BLOCKS, AND THE MARKERS MUST NOT NEST. generator_ablation.py
# prints the corpora table in two halves since the body structure pass -- the
# design rows into the appendix float, the outcome rows into what is now
# tab:ablation's panel (c). `gen_block` matches its marker as a SUBSTRING and
# takes the first hit, so the earlier pair "LaTeX body for the corpora" /
# "...for the corpora design" would have resolved both labels to whichever
# block printed first and reported a clean 9/9 while verifying one table
# twice. "outcome" and "design" are chosen because neither contains the other.
# Keep it that way. The outcome marker still says "table" for exactly this
# reason even though its block is now a panel; renaming it buys nothing and
# risks re-introducing a nesting collision.
#
# The two note markers are worded "LaTeX note under the <x> table" rather than
# "LaTeX body for ..." so that they nest with nothing in the list above, and
# they read as prose on the generator's own stdout.


def run(script, cached, args=()):
    out = f"/tmp/verify_{'_'.join((script[:-3], *args))}.txt"
    if cached and os.path.exists(out):
        return open(out).read()
    r = subprocess.run([sys.executable, script, *args], cwd=ANALYSIS,
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"{script} exited {r.returncode}:\n{r.stdout[-3000:]}\n"
                         f"{r.stderr[-3000:]}")
    open(out, "w").write(r.stdout)
    return r.stdout


def gen_block(text, marker):
    """The LaTeX rows printed under `marker`.

    Interleaved `%` notes are dropped -- the generators use them to label the
    header/grid/footer panels -- but a caption-facts line or the start of a
    second block ends the run.
    """
    lines = [l.rstrip() for l in text.split("\n")]
    try:
        i = next(k for k, l in enumerate(lines) if marker in l) + 1
    except StopIteration:
        raise SystemExit(f"marker not printed: {marker!r}")
    out = []
    while i < len(lines):
        s = lines[i]
        if s.lstrip().startswith("%"):
            # "LaTeX note" joins the terminators for the same reason "LaTeX
            # body" is one: a block must not run on into the next block's
            # marker. The blank line the generators print before each marker
            # already stops it, but that is a convention, not a guarantee.
            if ("caption fact" in s or "LaTeX body" in s
                    or "LaTeX note" in s):
                break
            i += 1
            continue
        if not s.strip():
            break
        out.append(s)
        i += 1
    return out


def _float_span(src, label):
    """Bracket the float that owns `label`, whichever float environment it is.

    Not just \\begin{table}: tab:conflict-gate is a half-width \\begin{wraptable}
    so the prose can run beside it, and searching backwards for \\begin{table}
    from its \\label silently walked past it into the PRECEDING float and
    returned that table's rows. The failure is not a clean miss -- it is a
    confident diff of one table against another table's generator, which is
    worse than no check. Take whichever opener is nearest before the label.
    """
    i = src.index("\\label{%s}" % label)
    opens = [(src.rindex(o, 0, i), o) for o in (r"\begin{table}",
                                                r"\begin{wraptable}")
             if o in src[:i]]
    if not opens:
        raise ValueError("no float opener before \\label{%s}" % label)
    start, opener = max(opens)
    closer = opener.replace("begin", "end")
    return start, src.index(closer, i)


# tabular or tabular*, because a float that is too wide gets rewritten into
# the starred form to take an explicit width, and a check that only knows the
# plain form does not report a narrower table -- it stops finding the table at
# all.  That is how tab:ablation-app went unverified: it was restructured into
# three tabular* panels, this raised ValueError on the missing \begin{tabular},
# and the run died there, taking every later float's check with it.
_TAB_BEGIN = re.compile(r"\\begin\{tabular\*?\}")
_TAB_END = re.compile(r"\\end\{tabular\*?\}")


def _tabular_spans(src, tb, te):
    """(start-of-body, end-of-body) for every tabular in one float, in order."""
    spans = []
    for b in _TAB_BEGIN.finditer(src, tb, te):
        e = _TAB_END.search(src, b.end(), te)
        if e is None:
            raise ValueError(
                "a \\begin{tabular} in this float is never closed before "
                "\\end{table}")
        spans.append((b.end(), e.start()))
    if not spans:
        raise ValueError("this float contains no tabular or tabular* body")
    return spans


def tabular_rows(src, label):
    """Every line of every tabular body in the float, in document order.

    All of them, not the first: a float split into sub-tables holds its
    generated rows across several environments, and reading only the first
    reports the rest as missing from a table that in fact contains them.
    """
    tb, te = _float_span(src, label)
    out = []
    for a, b in _tabular_spans(src, tb, te):
        out += [l.rstrip() for l in src[a:b].split("\n")[1:] if l.strip()]
    return out


def note_lines(src, label):
    """Everything between the LAST \\end{tabular} and \\end{table}.

    The last, not the first: a float that ever grows a second tabular should
    put its note after the last one, and picking the first would silently
    swallow the intervening table into the note region.
    """
    tb, te = _float_span(src, label)
    last = None
    for m in _TAB_END.finditer(src, tb, te):
        last = m
    if last is None:
        raise ValueError("this float contains no tabular or tabular* body")
    b = last.end()
    return [l.rstrip() for l in src[b:te].split("\n") if l.strip()]


def main():
    cached = "--cached" in sys.argv
    src = open(os.path.join(HERE, "main.tex")).read()
    ok = True
    nblocks = sum(len(b) for b in SPEC.values())
    for label, blocks in SPEC.items():
        region = {"tabular": tabular_rows(src, label),
                  "note": note_lines(src, label)}
        covered = {k: 0 for k in region}
        for i, block in enumerate(blocks):
            script, marker = block[0], block[1]
            where = block[2] if len(block) > 2 else "tabular"
            args = block[3] if len(block) > 3 else ()
            tex = region[where]
            gen = gen_block(run(script, cached, args), marker)
            hits = [k for k in range(len(tex) - len(gen) + 1)
                    if tex[k:k + len(gen)] == gen]
            good = len(hits) == 1
            ok &= good
            covered[where] += len(gen)
            # The hand-written count rides the LAST block of each label, once
            # every block's rows are accounted for, and it spans BOTH regions
            # so the minipage scaffolding around a note is visible too.
            hand = sum(len(v) - covered[k] for k, v in region.items())
            tail = (f"+{hand} hand-written header/rule/wrapper lines"
                    if i == len(blocks) - 1 else f"panel {i + 1}/{len(blocks)}")
            print(f"{label:<20} {' '.join((script, *args)):<29} "
                  f"gen={len(gen):>3} rows  "
                  f"{'OK' if good else 'MISMATCH':<8} {where:<7} {tail}")
            if not good:
                for x, y in zip(gen, tex[hits[0] if hits else 0:]):
                    if x != y:
                        print("     GEN:", repr(x))
                        print("     TEX:", repr(y))
                        break
                if len(hits) > 1:
                    print(f"     block appears {len(hits)} times; marker is ambiguous")
    print(f"\nall {nblocks} table bodies match their generators" if ok
          else "\nSOME BODIES DIVERGED -- re-paste from the generator")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
