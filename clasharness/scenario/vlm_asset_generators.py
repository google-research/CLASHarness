  def _render_chart_spec_matplotlib(self, chart_spec: dict[str, Any]) -> GeneratedAsset:
    import matplotlib.pyplot as plt
    import matplotlib.patches as patches
    import io
    import numpy as np

    title = str(chart_spec.get("title") or "PRO-VLM chart")
    chart_type = chart_spec.get("chart_type", "bar_chart")
    data = chart_spec.get("data", [])
    if not data and "rows" in chart_spec:
      data = chart_spec["rows"]

    def _safe_float(val: Any, default: float = 0.0) -> float:
      try:
        return float(val)
      except (ValueError, TypeError):
        return default

    # Use modern style baseline
    plt.style.use(
        "seaborn-v0_8-whitegrid"
        if "seaborn-v0_8-whitegrid" in plt.style.available
        else "default"
    )

    colors = [
        "#3b82f6",
        "#10b981",
        "#f59e0b",
        "#ef4444",
        "#8b5cf6",
        "#ec4899",
        "#06b6d4",
    ]

    def _apply_common_styles(ax):
      ax.spines["top"].set_visible(False)
      ax.spines["right"].set_visible(False)
      ax.spines["left"].set_color("#cccccc")
      ax.spines["bottom"].set_color("#cccccc")
      ax.grid(True, linestyle=":", alpha=0.35, color="#bbbbbb")

    def _render_to_ax(ax, spec, is_subplot=False):
      c_type = spec.get("chart_type", "bar_chart")
      t = str(spec.get("title") or "")
      d = spec.get("data", [])
      if not d and "rows" in spec:
        d = spec["rows"]

      # Handle dictionary-based standard Chart.js format
      if isinstance(d, dict) and "labels" in d and "datasets" in d:
        labels = [str(l) for l in d["labels"]]
        datasets = d["datasets"]
        if not datasets:
          ax.set_title(t, pad=15, fontsize=14 if is_subplot else 16, fontweight="bold")
          ax.axis("off")
          return

        is_line = c_type.startswith("line") or (datasets and datasets[0].get("type") == "line")

        if len(datasets) == 1:
          values = [_safe_float(val) for val in datasets[0].get("data", [])]
          if is_line:
            xs = np.arange(len(labels))
            ax.plot(
                xs,
                values,
                marker="o",
                linewidth=2.5,
                color=colors[0],
                markersize=6,
                markeredgecolor="white",
                markeredgewidth=1.5,
            )
            ax.fill_between(xs, values, color=colors[0], alpha=0.08)
            ax.set_xticks(xs)
            ax.set_xticklabels(labels, rotation=45, ha="right")
          else:
            bars = ax.bar(labels, values, color=colors[0])
            ax.bar_label(bars, fmt="%.1f", padding=3)
            ax.tick_params(axis="x", rotation=45)
          ax.set_ylabel(datasets[0].get("label", "Value"))
          _apply_common_styles(ax)
        else:
          xs = np.arange(len(labels))
          for k, ds in enumerate(datasets):
            vals = [_safe_float(val) for val in ds.get("data", [])]
            label = ds.get("label", f"Dataset {k}")
            if is_line:
              ax.plot(
                  xs,
                  vals,
                  marker="o",
                  linewidth=2.5,
                  label=label,
                  color=colors[k % len(colors)],
                  markersize=5,
                  markeredgecolor="white",
                  markeredgewidth=1,
              )
              ax.fill_between(xs, vals, color=colors[k % len(colors)], alpha=0.06)
            else:
              width = 0.8 / len(datasets)
              offset = (k - len(datasets) / 2.0 + 0.5) * width
              ax.bar(
                  xs + offset,
                  vals,
                  width,
                  label=label,
                  color=colors[k % len(colors)],
              )
          ax.set_xticks(xs)
          ax.set_xticklabels(labels, rotation=45, ha="right")
          ax.legend()
          _apply_common_styles(ax)
        ax.set_title(t, pad=15, fontsize=14 if is_subplot else 16, fontweight="bold")
        return

      if c_type == "bar_chart":
        labels = [
            str(item.get("label", f"item {i}")) for i, item in enumerate(d)
        ]
        values = [_safe_float(item.get("value", 0)) for item in d]
        bars = ax.bar(labels, values, color="#3b82f6")
        ax.bar_label(bars, fmt="%.1f", padding=3)
        ax.set_title(
            t, pad=15, fontsize=14 if is_subplot else 16, fontweight="bold"
        )
        ax.set_ylabel("Value")
        ax.tick_params(axis="x", rotation=45)
        _apply_common_styles(ax)
        ax.grid(True, linestyle="--", alpha=0.3, axis="y")

      elif c_type == "line_chart":
        labels = [
            str(item.get("label", f"time {i}")) for i, item in enumerate(d)
        ]
        values = [_safe_float(item.get("value", 0)) for item in d]
        xs = np.arange(len(labels))
        ax.plot(
            xs,
            values,
            marker="o",
            linewidth=2.5,
            color="#10b981",
            markersize=6,
            markeredgecolor="white",
            markeredgewidth=1.5,
        )
        ax.fill_between(xs, values, color="#10b981", alpha=0.08)
        ax.set_title(
            t, pad=15, fontsize=14 if is_subplot else 16, fontweight="bold"
        )
        ax.set_ylabel("Metric")
        _apply_common_styles(ax)
        for j, v in enumerate(values):
          ax.annotate(
              f"{v:.1f}",
              (xs[j], values[j]),
              textcoords="offset points",
              xytext=(0, 10),
              ha="center",
              fontsize=9,
          )
        ax.set_xticks(xs)
        ax.set_xticklabels(labels, rotation=45, ha="right")
        ax.margins(x=0.05, y=0.15)

      elif c_type == "multi_line_chart":
        series_names = spec.get("series_names", ["Series 1", "Series 2"])
        labels = [
            str(item.get("label", f"time {i}")) for i, item in enumerate(d)
        ]
        xs = np.arange(len(labels))
        series_values = [[] for _ in series_names]
        for item in d:
          vals = item.get("values", [])
          for k in range(len(series_names)):
            series_values[k].append(
                _safe_float(vals[k] if k < len(vals) else 0)
            )
        for k, name in enumerate(series_names):
          ax.plot(
              xs,
              series_values[k],
              marker="o",
              linewidth=2.5,
              label=name,
              color=colors[k % len(colors)],
              markersize=5,
              markeredgecolor="white",
              markeredgewidth=1,
          )
          ax.fill_between(xs, series_values[k], color=colors[k % len(colors)], alpha=0.06)
        ax.set_title(
            t, pad=15, fontsize=14 if is_subplot else 16, fontweight="bold"
        )
        ax.set_ylabel("Metric")
        _apply_common_styles(ax)
        ax.legend()
        ax.set_xticks(xs)
        ax.set_xticklabels(labels, rotation=45, ha="right")
        ax.margins(x=0.05, y=0.15)

      elif c_type == "grouped_bar_chart":
        series_names = spec.get("series_names", ["Series 1", "Series 2"])
        labels = [
            str(item.get("label", f"item {i}")) for i, item in enumerate(d)
        ]
        series_values = [[] for _ in series_names]
        for item in d:
          vals = item.get("values", [])
          for k in range(len(series_names)):
            series_values[k].append(
                _safe_float(vals[k] if k < len(vals) else 0)
            )
        x = np.arange(len(labels))
        width = 0.8 / len(series_names)
        for k, name in enumerate(series_names):
          offset = (k - len(series_names) / 2.0 + 0.5) * width
          ax.bar(
              x + offset,
              series_values[k],
              width,
              label=name,
              color=colors[k % len(colors)],
          )
        ax.set_title(
            t, pad=15, fontsize=14 if is_subplot else 16, fontweight="bold"
        )
        ax.set_ylabel("Value")
        ax.set_xticks(x)
        ax.set_xticklabels(labels, rotation=45, ha="right")
        ax.legend()
        _apply_common_styles(ax)
        ax.grid(True, linestyle="--", alpha=0.3, axis="y")

      elif c_type == "pie_chart":
        labels = [str(item.get("label", "")) for item in d]
        values = [_safe_float(item.get("value", 0)) for item in d]
        if sum(values) == 0:
          values = [1.0] * len(values)
        ax.pie(
            values,
            labels=labels,
            autopct="%1.1f%%",
            startangle=90,
            colors=colors[: len(values)],
            textprops={"fontsize": 10 if is_subplot else 11},
        )
        ax.set_title(
            t, pad=15, fontsize=14 if is_subplot else 16, fontweight="bold"
        )
        ax.axis("off")

      elif c_type == "stacked_bar_chart":
        series_names = spec.get("series_names", ["Series 1", "Series 2"])
        labels = [
            str(item.get("label", f"item {i}")) for i, item in enumerate(d)
        ]
        series_values = [[] for _ in series_names]
        for item in d:
          vals = item.get("values", [])
