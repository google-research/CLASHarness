# ---------------------------------------------------------------------------
# WD6: render quality floor.
#
# Loosened archetype/token sampling (WD2/WD4) means the renderer must never
# silently ship a broken page -- a *collapsed* screenshot (zero/degenerate
# dimensions) or a *blank* one (a single flat color / no ink). Every real
# render decodes its PNG and is checked against this floor before it becomes a
# ``GeneratedAsset``:
#   * non-degenerate dimensions (>= ``_MIN_RENDER_DIM`` px on each side), and
#   * non-empty content (a meaningful fraction of non-background pixels).
# Chart renders fall back to Matplotlib when the check trips (see
# ``render_chart_spec``); the raw-HTML LLM path raises so a broken token bundle
# is rejected rather than materialized. Set
# ``CLASHARNESS_DISABLE_RENDER_QUALITY_CHECK=1`` to bypass (debugging only).
# ---------------------------------------------------------------------------

_MIN_RENDER_DIM = 16
# A render is "blank" if fewer than this fraction of pixels differ from the
# single most common (background) color. Real UI pages -- even minimalist ones
# with text, thin borders, or a small chart -- clear this by a wide margin,
# while a collapsed/empty page sits at ~0.
_MIN_INK_FRACTION = 0.002


class RenderQualityError(RuntimeError):
  """A rendered asset failed the WD6 quality floor (blank/collapsed)."""


@dataclass(frozen=True)
class RenderQualityReport:
  ok: bool
  reason: str
  width: int
  height: int
  non_background_fraction: float
  # Number of distinct colors in the downscaled sample; -1 means "more than the
  # counting cap", i.e. unambiguously rich content.
  distinct_colors: int


def _render_quality_report(
    data: bytes,
    *,
    min_width: int = _MIN_RENDER_DIM,
    min_height: int = _MIN_RENDER_DIM,
    min_ink_fraction: float = _MIN_INK_FRACTION,
) -> RenderQualityReport:
  """Measure a rendered PNG against the quality floor (pure; no I/O or network).

  Returns a report rather than raising so callers and tests can inspect the
  measurements; ``_assert_render_quality`` wraps this to enforce the gate.

  The content estimate is resolution-independent: alpha is composited over an
  opaque white background (so a fully transparent page reads as blank rather
  than as a single "transparent" color) and the image is downscaled before the
  most-common-color analysis, which keeps the cost bounded for full-page shots.
  """
  import io as _io

  try:
    with Image.open(_io.BytesIO(data)) as im:
      im.load()
      width, height = im.width, im.height
      rgba = im.convert("RGBA")
  except Exception as exc:  # undecodable bytes are a hard quality failure
    return RenderQualityReport(
        ok=False,
        reason=f"undecodable image ({type(exc).__name__}: {exc})",
        width=0,
        height=0,
        non_background_fraction=0.0,
        distinct_colors=0,
    )

  if width < min_width or height < min_height:
    return RenderQualityReport(
        ok=False,
        reason=(
            f"degenerate dimensions {width}x{height} "
            f"(min {min_width}x{min_height})"
        ),
        width=width,
        height=height,
        non_background_fraction=0.0,
        distinct_colors=-1,
    )

  background = Image.new("RGBA", rgba.size, (255, 255, 255, 255))
  flattened = Image.alpha_composite(background, rgba).convert("RGB")
  sample = flattened.copy()
  sample.thumbnail((200, 200))

  colors = sample.getcolors(maxcolors=200 * 200)
  if colors is None:
    # More distinct colors than the counting cap -> unambiguously rich content.
    return RenderQualityReport(
        ok=True,
        reason="ok (rich color content)",
        width=width,
        height=height,
        non_background_fraction=1.0,
        distinct_colors=-1,
    )

  total = sum(count for count, _ in colors) or 1
  background_count = max(count for count, _ in colors)
  non_background_fraction = 1.0 - background_count / total
  distinct_colors = len(colors)

  if distinct_colors <= 1 or non_background_fraction < min_ink_fraction:
    return RenderQualityReport(
        ok=False,
        reason=(
            f"blank render: {non_background_fraction:.4%} non-background pixels "
            f"across {distinct_colors} color(s) (min {min_ink_fraction:.2%})"
        ),
        width=width,
        height=height,
        non_background_fraction=non_background_fraction,
        distinct_colors=distinct_colors,
    )

  return RenderQualityReport(
      ok=True,
      reason="ok",
      width=width,
      height=height,
      non_background_fraction=non_background_fraction,
      distinct_colors=distinct_colors,
  )


def _assert_render_quality(data: bytes, *, context: str) -> None:
  """Raise ``RenderQualityError`` if ``data`` fails the WD6 quality floor.

  Honors the ``CLASHARNESS_DISABLE_RENDER_QUALITY_CHECK=1`` escape hatch.
  """
  if getenv("CLASHARNESS_DISABLE_RENDER_QUALITY_CHECK") == "1":
    return
  report = _render_quality_report(data)
  if not report.ok:
    raise RenderQualityError(f"{context}: {report.reason}")


