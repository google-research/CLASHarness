def _prepare_render_dir(html_content: str, tmpdir: Path) -> str:
  """Prepare temp directory by copying local JS libs and replacing CDN URLs."""
  tmp_libs_dir = tmpdir / "libs"
  tmp_libs_dir.mkdir(parents=True, exist_ok=True)

  root_third_party = Path(__file__).parents[2] / "third_party"
  src_libs_dir = Path(__file__).parent / "templates" / "libs"
  for candidate in [root_third_party / "tailwindcss" / "tailwind.js", src_libs_dir / "tailwind.js"]:
    if candidate.exists():
      shutil.copy(candidate, tmp_libs_dir / "tailwind.js")
      break
  for candidate in [root_third_party / "chartjs" / "chart.js", src_libs_dir / "chart.js"]:
    if candidate.exists():
      shutil.copy(candidate, tmp_libs_dir / "chart.js")
      break

  content = html_content
  content = content.replace("https://cdn.tailwindcss.com", "libs/tailwind.js")
  content = content.replace("https://cdn.jsdelivr.net/npm/chart.js", "libs/chart.js")
  # Handle alternate npm/dist versions that might be generated by LLM
  content = content.replace("https://cdn.jsdelivr.net/npm/chart.js@4.4.1/dist/chart.umd.js", "libs/chart.js")
  content = content.replace("https://cdn.jsdelivr.net/npm/chart.js@4.4.0/dist/chart.umd.js", "libs/chart.js")
  content = content.replace("https://cdn.jsdelivr.net/npm/chart.js@4.3.0/dist/chart.umd.js", "libs/chart.js")
  content = content.replace("https://cdn.jsdelivr.net/npm/chart.js@4", "libs/chart.js")

  return content


