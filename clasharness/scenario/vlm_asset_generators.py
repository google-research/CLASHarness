class CodeChartGenerator:
  """Render controlled chart/table/dashboard assets locally."""

  def render_chart_spec(self, chart_spec: dict[str, Any]) -> GeneratedAsset:
    chrome_path = shutil.which("google-chrome")
    if chrome_path:
      try:
        print("Rendering chart via HTML/Chrome...", flush=True)
        return self._render_chart_spec_html(chart_spec)
      except Exception as exc:
        print(f"Warning: HTML/Chrome chart rendering failed: {exc}. Falling back to Matplotlib...", flush=True)
        return self._render_chart_spec_matplotlib(chart_spec)
    else:
      print("Warning: google-chrome not found. Falling back to Matplotlib...", flush=True)
      return self._render_chart_spec_matplotlib(chart_spec)

  def _render_chart_spec_html(self, chart_spec: dict[str, Any]) -> GeneratedAsset:
    # Resolve relative template path
    template_path = Path(__file__).parent / "templates" / "chart_template.html"
    if not template_path.exists():
      raise FileNotFoundError(f"Chart template not found at {template_path}")
    template_content = template_path.read_text(encoding="utf-8")

    # Inject chart spec JSON
    injected_spec = f"window.CHART_SPEC = {json.dumps(chart_spec, ensure_ascii=False)};"
    html_content = template_content.replace("// INJECTED SPEC:", injected_spec)

    with tempfile.TemporaryDirectory(prefix="openclaw_chart_chrome_") as tmp:
      tmpdir = Path(tmp)
      html_file = tmpdir / "chart.html"
      png_file = tmpdir / "chart.png"
      prepared_html = _prepare_render_dir(html_content, tmpdir)
      html_file.write_text(prepared_html, encoding="utf-8")

      # Launch headless Chrome screenshot
      cmd = [
          "google-chrome",
          "--headless",
          # Safe to disable Chrome sandbox here because we only render local,
          # trusted HTML file content generated programmatically from templates.
          "--no-sandbox",
          f"--screenshot={png_file}",
          _get_chrome_window_size_arg(),
          _get_chrome_scale_arg(),
          f"file://{html_file.resolve()}",
      ]
      proc = subprocess.run(
          cmd,
          capture_output=True,
          text=True,
          timeout=15,
          env={"PATH": os.environ.get("PATH", "")},
          check=False,
      )
      if proc.returncode != 0:
        raise RuntimeError(
            f"Chrome rendering failed (exit={proc.returncode}): {proc.stderr.strip() or proc.stdout.strip()}"
        )
      if not png_file.exists():
        raise RuntimeError("Chrome screenshot did not generate output file")

      png_bytes = png_file.read_bytes()
      _assert_render_quality(png_bytes, context="chart html_chrome render")
      return GeneratedAsset(
          data=png_bytes,
          mime_type="image/png",
          extension="png",
          metadata={
              "provider": "code_chart",
              "renderer": "html_chrome",
              "chart_type": chart_spec.get("chart_type", "bar_chart"),
          },
          chart_spec=dict(chart_spec),
      )

